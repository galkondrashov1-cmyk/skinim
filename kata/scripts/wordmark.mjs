// Generates vector paths for the KATA wordmark and slogan from the brand fonts,
// so the logotype renders identically in the app, icons and launch images.
import opentype from 'opentype.js';
import { readFileSync, writeFileSync } from 'node:fs';

const font = (f) => opentype.parse(readFileSync(new URL(`../node_modules/@fontsource/${f}`, import.meta.url)).buffer);
const bsc600 = font('barlow-semi-condensed/files/barlow-semi-condensed-latin-600-normal.woff');
const bsc500 = font('barlow-semi-condensed/files/barlow-semi-condensed-latin-500-normal.woff');

const n = (v) => {
  const r = Math.round(v * 100) / 100;
  if (!Number.isFinite(r)) throw new Error('non-finite coordinate');
  return String(r);
};

/** Serialise path commands directly (opentype.js toPathData can emit NaN). */
function pathData(p) {
  return p.commands
    .map((c) => {
      switch (c.type) {
        case 'M':
        case 'L':
          return `${c.type}${n(c.x)} ${n(c.y)}`;
        case 'Q':
          return `Q${n(c.x1)} ${n(c.y1)} ${n(c.x)} ${n(c.y)}`;
        case 'C':
          return `C${n(c.x1)} ${n(c.y1)} ${n(c.x2)} ${n(c.y2)} ${n(c.x)} ${n(c.y)}`;
        case 'Z':
          return 'Z';
        default:
          throw new Error(`unknown command ${c.type}`);
      }
    })
    .join('');
}

function setText(f, text, size, tracking) {
  let x = 0;
  const parts = [];
  const all = new opentype.Path();
  const glyphs = f.stringToGlyphs(text);
  glyphs.forEach((g, i) => {
    const p = g.getPath(x, size * 0.8, size);
    parts.push(pathData(p));
    all.extend(p);
    x += (g.advanceWidth / f.unitsPerEm) * size + (i < glyphs.length - 1 ? tracking * size : 0);
  });
  const box = all.getBoundingBox();
  return { d: parts.join(' '), width: Number(x.toFixed(2)), height: size, box: { x1: +box.x1.toFixed(2), y1: +box.y1.toFixed(2), x2: +box.x2.toFixed(2), y2: +box.y2.toFixed(2) } };
}

const word = setText(bsc600, 'KATA', 100, 0.22);
const slogan = setText(bsc500, 'REHEARSE EVERY TRADE', 100, 0.16);
const out = `// Generated by scripts/wordmark.mjs — do not edit by hand.
export const WORDMARK = ${JSON.stringify(word)} as const;
export const SLOGAN_PATH = ${JSON.stringify(slogan)} as const;
`;
writeFileSync(new URL('../src/brand/wordmark-paths.ts', import.meta.url), out);
console.log('wordmark', word.width, word.box, 'slogan', slogan.width);
